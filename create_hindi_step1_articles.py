def make_rich_text(segments):
    rich_text = []
    for s in segments:
        annotations = {}
        if s.get("bold"):
            annotations["bold"] = True
        if s.get("italic"):
            annotations["italic"] = True
        rich_text.append({
            "type": "text",
            "text": {"content": s["text"]},
            "annotations": annotations
        })
    return rich_text

def build_hindi_blocks(art):
    children = []
    # 1. Globe callout
    callout_text = f"Language: hi\nLabel: {art['label']}\nTitle: {art['title']}\nDescription: {art['description']}"
    children.append({
        "type": "callout",
        "callout": {
            "icon": {"type": "emoji", "emoji": "\U0001f310"},
            "rich_text": [{"type": "text", "text": {"content": callout_text}}]
        }
    })
    # 2. Sections
    for block_type, content in art["sections"]:
        if block_type == "heading_1":
            children.append({
                "type": "heading_1",
                "heading_1": {"rich_text": [{"type": "text", "text": {"content": content}}]}
            })
        elif block_type == "paragraph":
            children.append({
                "type": "paragraph",
                "paragraph": {"rich_text": make_rich_text(content)}
            })
        elif block_type == "bulleted_list_item":
            children.append({
                "type": "bulleted_list_item",
                "bulleted_list_item": {"rich_text": make_rich_text(content)}
            })
    # 3. Divider
    children.append({"type": "divider", "divider": {}})
    # 4. AI disclosure in Hindi
    children.append({
        "type": "paragraph",
        "paragraph": {
            "rich_text": [
                {
                    "type": "text",
                    "text": {"content": "एआई प्रकटीकरण: एआई (ChatGPT) की सहायता से लिखा गया। आपसे अनुरोध है कि त्रुटियों और चूकों की ओर ध्यान दिलाएँ।"},
                    "annotations": {"italic": True}
                }
            ]
        }
    })
    return children

def create_hindi_pages():
    for art in HINDI_ARTICLES:
        slug = art["parent_slug"]
        res = notion.databases.query(database_id=db_id, filter={"property": "Id", "title": {"equals": slug}})
        pages = res.get("results", [])
        if not pages:
            print(f"Parent page not found for '{slug}'")
            continue
        parent_id = pages[0]['id']

        # Check existing child pages inside parent
        blocks = notion.blocks.children.list(block_id=parent_id).get('results', [])
        for b in blocks:
            if b.get('type') == 'child_page' and 'हिन्दी' in b.get('child_page', {}).get('title', ''):
                print(f"Deleting existing Hindi child page in '{slug}' ({b['id']})...")
                notion.blocks.delete(block_id=b['id'])

        print(f"Creating Hindi translation child page for '{slug}'...")
        child = notion.pages.create(
            parent={"page_id": parent_id},
            properties={
                "title": [{"type": "text", "text": {"content": "हिन्दी (hi)"}}]
            },
            children=build_hindi_blocks(art)
        )
        print(f"  Created Hindi child for '{slug}': {child['id']}")

if __name__ == "__main__":
    create_hindi_pages()
